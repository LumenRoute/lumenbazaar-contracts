import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  COVERAGE_SCHEMA_VERSION,
  evaluateCoverageThresholds,
  summarizeLlvmCovExport,
  validateCoverageThresholds,
} from "./lib/coverage.mjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const thresholdsPath = join(repoRoot, "artifacts", "coverage", "thresholds.json");
const defaultReportPath = join(repoRoot, "artifacts", "coverage", "report.json");
const reportPath = optionValue("--report") ?? defaultReportPath;
const checkOnlyInput = optionValue("--check-only");

const thresholds = JSON.parse(readFileSync(thresholdsPath, "utf8"));
validateCoverageThresholds(thresholds);

const llvmExport = checkOnlyInput
  ? JSON.parse(readFileSync(resolvePath(checkOnlyInput), "utf8"))
  : collectNativeCoverage();

const summary = summarizeLlvmCovExport(llvmExport, repoRoot);
const evaluation = evaluateCoverageThresholds(summary, thresholds);

console.log(`Native production coverage (branch metric: ${summary.branchMetric}):`);
console.log("Contract | Modules | Line % | Branch % | Function %");
for (const row of summary.contracts) {
  console.log(
    `${row.contract} | ${row.moduleCount} | ${row.lines.percent}% (${row.lines.covered}/${row.lines.count}) | ` +
      `${row.branches.percent}% (${row.branches.covered}/${row.branches.count}) | ` +
      `${row.functions.percent}% (${row.functions.covered}/${row.functions.count})`,
  );
}

console.log("\nCritical module thresholds:");
console.log("Module | Line % (min) | Branch % (min) | Result");
for (const row of evaluation.moduleResults) {
  console.log(
    `${row.path} | ${row.observedLinePercent ?? "n/a"}% (${row.minLinePercent}%) | ` +
      `${row.observedBranchPercent ?? "n/a"}% (${row.minBranchPercent}%) | ${row.passed ? "PASS" : "FAIL"}`,
  );
}

const report = {
  schemaVersion: COVERAGE_SCHEMA_VERSION,
  thresholdsSource: relative(repoRoot, thresholdsPath).replaceAll("\\", "/"),
  branchMetric: summary.branchMetric,
  wasmReleaseInstrumented: false,
  passed: evaluation.passed,
  totals: summary.totals,
  contracts: summary.contracts,
  modules: summary.modules,
  contractChecks: evaluation.contractResults,
  criticalModuleChecks: evaluation.moduleResults,
  failures: evaluation.failures,
};

const output = resolvePath(reportPath);
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, `${JSON.stringify(report, null, 2)}\n`, "utf8");
console.log(`\nCoverage report written to ${output}`);

if (!evaluation.passed) {
  throw new Error(
    `Native contract coverage check failed:\n- ${evaluation.failures.join("\n- ")}`,
  );
}

console.log("Native contract coverage check passed.");

function collectNativeCoverage() {
  const { llvmProfdata, llvmCov } = locateLlvmTools();
  const coverageTargetDir = join(repoRoot, "target", "coverage");
  const profrawDir = join(coverageTargetDir, "profraw");
  const profdataPath = join(coverageTargetDir, "lumenbazaar.profdata");

  rmSync(profrawDir, { recursive: true, force: true });
  mkdirSync(profrawDir, { recursive: true });

  const env = {
    ...process.env,
    CARGO_TARGET_DIR: coverageTargetDir,
    RUSTFLAGS: `${process.env.RUSTFLAGS ? `${process.env.RUSTFLAGS} ` : ""}-C instrument-coverage`,
    LLVM_PROFILE_FILE: join(profrawDir, "lumenbazaar-%p-%m.profraw"),
    LUMENBAZAAR_PROPERTY_CASES: process.env.LUMENBAZAAR_PROPERTY_CASES ?? "128",
  };

  const buildOutput = execFileSync(
    "cargo",
    ["test", "--workspace", "--all-features", "--no-run", "--message-format=json"],
    {
      cwd: repoRoot,
      env,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    },
  );

  const executables = [];
  for (const line of buildOutput.split(/\r?\n/)) {
    if (!line.startsWith("{")) continue;
    const msg = JSON.parse(line);
    if (msg.reason === "compiler-artifact" && msg.executable && msg.profile?.test) {
      executables.push(msg.executable);
    }
  }
  const uniqueExecutables = [...new Set(executables)].sort();
  if (uniqueExecutables.length === 0) {
    throw new Error("No workspace test executables were produced for coverage instrumentation.");
  }

  execFileSync("cargo", ["test", "--workspace", "--all-features"], {
    cwd: repoRoot,
    env,
    stdio: "inherit",
  });

  const profrawFiles = readdirSync(profrawDir)
    .filter((file) => file.endsWith(".profraw"))
    .sort()
    .map((file) => join(profrawDir, file));
  if (profrawFiles.length === 0) {
    throw new Error("No .profraw coverage profiles were generated by native tests.");
  }

  execFileSync(llvmProfdata, ["merge", "-sparse", ...profrawFiles, "-o", profdataPath], {
    cwd: repoRoot,
    stdio: "inherit",
  });

  const objectArgs = [];
  for (const exe of uniqueExecutables) {
    objectArgs.push("--object", exe);
  }

  const exportText = execFileSync(
    llvmCov,
    [
      "export",
      "--format=text",
      "--summary-only",
      `--instr-profile=${profdataPath}`,
      ...objectArgs,
      "--ignore-filename-regex=(/.cargo/registry|/rustc/|\\\\.cargo\\\\registry|\\\\rustc\\\\)",
    ],
    {
      cwd: repoRoot,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "pipe"],
    },
  );

  return JSON.parse(exportText);
}

function locateLlvmTools() {
  const sysroot = execFileSync("rustc", ["--print", "sysroot"], { encoding: "utf8" }).trim();
  const rustcVersion = execFileSync("rustc", ["-vV"], { encoding: "utf8" });
  const hostMatch = rustcVersion.match(/^host:\s*(.+)$/m);
  if (!hostMatch) {
    throw new Error("Unable to determine rustc host triple.");
  }
  const host = hostMatch[1].trim();
  const ext = process.platform === "win32" ? ".exe" : "";
  const binDir = join(sysroot, "lib", "rustlib", host, "bin");
  const llvmProfdata = join(binDir, `llvm-profdata${ext}`);
  const llvmCov = join(binDir, `llvm-cov${ext}`);

  if (!existsSync(llvmProfdata) || !existsSync(llvmCov)) {
    throw new Error(
      `Missing llvm-tools-preview binaries in ${binDir}. Install with: rustup component add llvm-tools-preview`,
    );
  }
  return { llvmProfdata, llvmCov };
}

function resolvePath(input) {
  return isAbsolute(input) ? input : resolve(repoRoot, input);
}

function optionValue(name) {
  const index = process.argv.indexOf(name);
  if (index === -1) return null;
  const value = process.argv[index + 1];
  if (!value || value.startsWith("--")) {
    throw new Error(`${name} requires a value.`);
  }
  return value;
}
