import { execFileSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(repoRoot, "artifacts", "resource-usage");

const output = execFileSync(
  "cargo",
  [
    "test",
    "-p",
    "upto-session",
    "resource_usage_",
    "--",
    "--nocapture",
    "--test-threads=1",
  ],
  {
    cwd: repoRoot,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "inherit"],
  },
);

process.stdout.write(output);

const rows = output
  .split(/\r?\n/)
  .map((line) => line.match(/RESOURCE_USAGE_JSON (\{.*\})/))
  .filter(Boolean)
  .map((match) => JSON.parse(match[1]));

if (rows.length !== 4) {
  throw new Error(`Expected 4 resource rows, received ${rows.length}`);
}

mkdirSync(outDir, { recursive: true });

writeFileSync(
  join(outDir, "upto-session.json"),
  `${JSON.stringify(
    {
      source: "cargo test -p upto-session resource_usage_ -- --nocapture --test-threads=1",
      note:
        "Local Soroban SDK native estimates; live RPC simulation is required before production fee budgeting.",
      rows,
    },
    null,
    2,
  )}\n`,
  "utf8",
);

const table = [
  "| Operation | Instructions | Memory bytes | Disk reads | Memory reads | Writes | Disk read bytes | Write bytes | Event bytes | Rent ledger bytes | Rent bumps | Estimated fee stroops |",
  "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
  ...rows.map(
    (row) =>
      `| ${row.operation} | ${row.instructions} | ${row.mem_bytes} | ${row.disk_read_entries} | ${row.memory_read_entries} | ${row.write_entries} | ${row.disk_read_bytes} | ${row.write_bytes} | ${row.contract_events_size_bytes} | ${row.persistent_rent_ledger_bytes} | ${row.persistent_entry_rent_bumps} | ${row.estimated_fee_stroops} |`,
  ),
].join("\n");

writeFileSync(
  join(outDir, "upto-session.md"),
  `# Upto Session Resource Usage

Generated by \`node scripts/report-resource-usage.mjs\`.

These are local Soroban SDK native estimates from test invocations. They are useful for regression tracking and rough expectations, but they do not replace RPC simulation on the target network before deployment.

${table}
`,
  "utf8",
);
