import assert from "node:assert/strict";
import { test } from "node:test";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildCycloneDxSbom,
  buildProvenance,
  cargoPurl,
  isWorkspacePackage,
  parseCargoLock,
  readLockfile,
  readToolchain,
  sha256Hex,
  verifyProvenance,
} from "./provenance.mjs";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

const LOCK = `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "demo-workspace"
version = "0.1.0"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "1.0.219"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "5a15f179cd60c4584b8a8c596927aadc462e27f2ca70c04e0071964a73ba7a75"
dependencies = [
 "serde_derive",
]
`;

const TOOLCHAIN = {
  rust: "1.93.1",
  wasmTarget: "wasm32v1-none",
  sorobanSdk: "28.0.0",
  stellarCli: "28.0.0",
  node: "22.12.0",
  contractVersion: "0.3.0",
};

function consistentFixture() {
  const packages = parseCargoLock(LOCK);
  const lockfile = { path: "Cargo.lock", sha256: sha256Hex(LOCK) };
  const artifact = {
    name: "upto_session",
    file: "target/wasm32v1-none/release/upto_session.wasm",
    sha256: "a".repeat(64),
    sizeBytes: 1234,
    sourceCommit: "b".repeat(40),
    lockfileSha256: lockfile.sha256,
    toolchain: { rust: TOOLCHAIN.rust, wasmTarget: TOOLCHAIN.wasmTarget, sorobanSdk: TOOLCHAIN.sorobanSdk },
  };
  const provenance = buildProvenance({
    repository: "LumenRoute/lumenbazaar-contracts",
    sourceCommit: artifact.sourceCommit,
    lockfile,
    toolchain: TOOLCHAIN,
    workspaceCrates: ["demo-workspace"],
    artifacts: [artifact],
  });
  const sbom = buildCycloneDxSbom({
    packages,
    repository: "LumenRoute/lumenbazaar-contracts",
    sourceCommit: artifact.sourceCommit,
    lockfile,
    toolchain: TOOLCHAIN,
  });
  return { packages, lockfile, provenance, sbom, artifact };
}

function verify(overrides) {
  const fixture = consistentFixture();
  return verifyProvenance({
    provenance: fixture.provenance,
    sbom: fixture.sbom,
    packages: fixture.packages,
    lockfileSha256: fixture.lockfile.sha256,
    toolchain: TOOLCHAIN,
    artifacts: [fixture.artifact],
    expectedWasmFiles: ["upto_session"],
    ...overrides,
  });
}

test("parseCargoLock reads registry and workspace packages with dependencies", () => {
  const packages = parseCargoLock(LOCK);
  assert.equal(packages.length, 2);
  const serde = packages.find((entry) => entry.name === "serde");
  assert.equal(serde.version, "1.0.219");
  assert.deepEqual(serde.dependencies, ["serde_derive"]);
  assert.equal(serde.checksum, "5a15f179cd60c4584b8a8c596927aadc462e27f2ca70c04e0071964a73ba7a75");
  assert.equal(isWorkspacePackage(serde), false);
  assert.equal(isWorkspacePackage(packages.find((entry) => entry.name === "demo-workspace")), true);
});

test("buildCycloneDxSbom marks workspace crates and records checksums", () => {
  const { sbom } = consistentFixture();
  assert.equal(sbom.bomFormat, "CycloneDX");
  const workspace = sbom.components.find((component) => component.purl === cargoPurl("demo-workspace", "0.1.0"));
  assert.ok(workspace.properties.some((property) => property.name === "lumenbazaar:workspace"));
  const serde = sbom.components.find((component) => component.name === "serde");
  assert.deepEqual(serde.hashes, [
    { alg: "SHA-256", content: "5a15f179cd60c4584b8a8c596927aadc462e27f2ca70c04e0071964a73ba7a75" },
  ]);
});

test("verifyProvenance accepts a consistent bundle", () => {
  assert.deepEqual(verify({}), []);
});

test("verifyProvenance fails closed on a lockfile mismatch", () => {
  const failures = verify({ lockfileSha256: "f".repeat(64) });
  assert.ok(failures.some((failure) => failure.includes("lockfile digest")));
});

test("verifyProvenance fails closed on an artifact checksum mismatch", () => {
  const failures = verify({ artifacts: [{ name: "upto_session", sha256: "c".repeat(64), sizeBytes: 1234 }] });
  assert.ok(failures.some((failure) => failure.includes("checksum")));
});

test("verifyProvenance fails closed when a built WASM has no provenance entry", () => {
  const failures = verify({ expectedWasmFiles: ["upto_session", "test_token"] });
  assert.ok(failures.some((failure) => failure.includes("test_token") && failure.includes("no provenance")));
});

test("verifyProvenance fails closed when the SBOM drops a transitive crate", () => {
  const fixture = consistentFixture();
  const pruned = { ...fixture.sbom, components: fixture.sbom.components.slice(0, 1) };
  const failures = verify({ sbom: pruned });
  assert.ok(failures.some((failure) => failure.includes("components")));
  assert.ok(failures.some((failure) => failure.includes("pkg:cargo/serde")));
});

test("repository lockfile and toolchain parse from pinned files", () => {
  const lockfile = readLockfile(repoRoot);
  assert.ok(lockfile.packages.length > 100);
  assert.ok(lockfile.packages.some((entry) => entry.name === "upto-session" && isWorkspacePackage(entry)));
  assert.match(lockfile.sha256, /^[0-9a-f]{64}$/);
  const toolchain = readToolchain(repoRoot);
  assert.equal(toolchain.rust, "1.93.1");
  assert.equal(toolchain.wasmTarget, "wasm32v1-none");
  assert.equal(toolchain.sorobanSdk, "28.0.0");
  assert.equal(toolchain.contractVersion, "0.3.0");
});
