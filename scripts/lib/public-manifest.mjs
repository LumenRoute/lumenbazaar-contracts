import { testnetNetwork } from "./deployment-evidence.mjs";

export const publicContractNames = ["upto-session", "test-token", "policy-wallet-example"];

const hashPattern = /^[a-f0-9]{64}$/;
const hashFields = new Set([
  "artifactSha256",
  "interfaceSha256",
  "resourceHash",
  "sessionId",
  "transactionHash",
  "usageHash",
  "wasmHash",
]);
const aliasConventionPattern =
  /lumenbazaar-[a-z0-9-]*(?:deployer|admin|owner|buyer|seller|attacker|wrong)[a-z0-9-]*/;
const secretRules = [
  { rule: "stellar-secret-seed", pattern: /(?<![A-Z2-7])S[A-Z2-7]{55}(?![A-Z2-7])/ },
  { rule: "mnemonic-phrase", pattern: /(?<![a-z])(?:[a-z]{3,8} ){11,}[a-z]{3,8}(?![a-z])/ },
  { rule: "absolute-local-path", pattern: /(?:\/home\/|\/Users\/|(?<![A-Za-z])[A-Za-z]:[\\/]|file:\/\/|~[\\/])/ },
  {
    rule: "stellar-config-path",
    pattern: /(?:^|[\\/~\s"'])\.(?:stellar|soroban)(?:[\\/]|$)|[\\/]\.config[\\/]stellar/,
  },
  { rule: "xdr-envelope", pattern: /[A-Za-z0-9+/]{80,}={0,2}/ },
  { rule: "local-identity-alias", pattern: aliasConventionPattern },
];
const privateKeyHexPattern = /(?<![0-9a-fA-F])(?:0x)?[0-9a-fA-F]{64}(?![0-9a-fA-F])/;

// Fields that the local scripts record for operators but must never be published.
const knownLocalContractFields = new Set(["alias", "name", "network", "wasm"]);
const knownLocalTopLevelFields = new Set(["generatedAt", "localAliases", "network"]);

const deploymentLimitations = [
  "This manifest proves deployment and initialization only; live rejection evidence is published separately.",
  "LBT is a custom test-only token and must not be represented as Circle USDC.",
  "Testnet evidence is not mainnet evidence.",
  "Generated by scripts/testnet/generate-public-manifest.mjs from network receipts; ledgers and timestamps come from the network, not local clocks.",
];

export class ManifestGenerationError extends Error {
  constructor(message, paths = []) {
    super(paths.length > 0 ? `${message}: ${paths.join(", ")}` : message);
    this.paths = paths;
  }
}

export function scanForSecrets(value, { aliases = [] } = {}) {
  const findings = [];
  const aliasValues = [...new Set(aliases)].filter((alias) => typeof alias === "string" && alias.length >= 3);
  visit(value, "$");
  return findings;

  function visit(node, path) {
    if (Array.isArray(node)) {
      node.forEach((entry, index) => visit(entry, `${path}[${index}]`));
      return;
    }
    if (node !== null && typeof node === "object") {
      Object.keys(node).forEach((key, index) => {
        if (scanString(key, key).length > 0) {
          findings.push({ path: `${path}.<key #${index}>`, rule: scanString(key, key)[0] });
        }
        visit(node[key], `${path}.${safeKey(key)}`);
      });
      return;
    }
    if (typeof node === "string") {
      const field = path.match(/\.([A-Za-z0-9_-]+)$/)?.[1] ?? "";
      for (const rule of scanString(node, field)) {
        findings.push({ path, rule });
      }
    }
  }

  function scanString(text, field) {
    const rules = secretRules.filter(({ pattern }) => pattern.test(text)).map(({ rule }) => rule);
    const isPublicHash = hashFields.has(field) && hashPattern.test(text);
    if (!isPublicHash && privateKeyHexPattern.test(text)) {
      rules.push("private-key-hex");
    }
    if (aliasValues.some((alias) => text.includes(alias))) {
      rules.push("local-identity-alias");
    }
    return [...new Set(rules)];
  }

  function safeKey(key) {
    return scanString(key, key).length > 0 ? "<redacted key>" : key;
  }
}

export function serializeDeterministic(value) {
  return `${JSON.stringify(sortKeys(value), null, 2)}\n`;
}

export function buildPublicDeploymentManifest(local, receipts) {
  const dropped = [];
  const unknown = [];
  requireTestnet(local.network);

  for (const key of Object.keys(local)) {
    if (knownLocalTopLevelFields.has(key)) {
      dropped.push(key);
    } else if (!["admin", "contracts", "deployer", "sourceCommit", "toolchain"].includes(key)) {
      unknown.push(key);
    }
  }

  const toolchain = pick(local.toolchain ?? {}, ["rustc", "sorobanSdk", "stellarCli", "stellarXdr", "target"], "toolchain", unknown);
  const contracts = {};
  for (const [name, contract] of Object.entries(local.contracts ?? {})) {
    if (!publicContractNames.includes(name)) {
      unknown.push(`contracts.${name}`);
      continue;
    }
    const path = `contracts.${name}`;
    const output = {};
    for (const key of Object.keys(contract)) {
      if (knownLocalContractFields.has(key)) {
        dropped.push(`${path}.${key}`);
      } else if (
        ![
          "artifactSha256",
          "asset",
          "contractId",
          "deploy",
          "initialize",
          "interfaceSha256",
          "interfaceVersion",
          "upload",
          "wasmHash",
        ].includes(key)
      ) {
        unknown.push(`${path}.${key}`);
      }
    }
    Object.assign(
      output,
      pick(contract, ["artifactSha256", "contractId", "interfaceSha256", "interfaceVersion", "wasmHash"], path, []),
    );
    if (contract.asset !== undefined) {
      output.asset = pick(contract.asset, ["code", "decimals", "purpose"], `${path}.asset`, unknown);
    }
    for (const operation of ["upload", "deploy", "initialize"]) {
      const allowed = operation === "upload" ? ["transactionHash", "wasmHash"] : ["transactionHash"];
      const recorded = pick(contract[operation] ?? {}, allowed, `${path}.${operation}`, unknown);
      const expectedSource = operation === "initialize" ? local.admin : local.deployer;
      const receipt = requireReceipt(receipts, recorded.transactionHash, `${path}.${operation}`);
      requireSuccessfulReceipt(receipt, `${path}.${operation}`);
      if (receipt.sourceAccount !== expectedSource) {
        throw new ManifestGenerationError(
          `${path}.${operation} was signed by an account other than the recorded ${operation === "initialize" ? "admin" : "deployer"}`,
        );
      }
      output[operation] = { ...recorded, ledger: receipt.ledger, createdAt: receipt.createdAt };
    }
    contracts[name] = output;
  }

  failOnUnknown(unknown);
  if (Object.keys(contracts).length === 0) {
    throw new ManifestGenerationError("The local manifest contains no publishable contracts");
  }

  const document = {
    schemaVersion: 2,
    environment: "testnet",
    network: { ...testnetNetwork },
    sourceCommit: local.sourceCommit,
    deployer: local.deployer,
    admin: local.admin,
    toolchain,
    contracts,
    limitations: deploymentLimitations,
  };
  return { document, dropped: dropped.sort(), date: earliestDate(collectCreatedAt(contracts)) };
}

export function buildPublicLiveEvidence(local, receipts) {
  const dropped = [];
  const unknown = [];
  requireTestnet(local.network);

  const topLevel = [
    "actors",
    "asset",
    "cases",
    "contractId",
    "deploymentManifest",
    "setupTransactions",
    "sourceCommit",
  ];
  for (const key of Object.keys(local)) {
    if (knownLocalTopLevelFields.has(key)) {
      dropped.push(key);
    } else if (!topLevel.includes(key)) {
      unknown.push(key);
    }
  }

  const setupTransactions = (local.setupTransactions ?? []).map((entry, index) => {
    const path = `setupTransactions[${index}]`;
    const recorded = pick(entry, ["name", "sessionId", "transactionHash"], path, unknown);
    const receipt = requireReceipt(receipts, recorded.transactionHash, path);
    requireSuccessfulReceipt(receipt, path);
    return { ...recorded, ...receiptFields(receipt), expectedSuccessful: true };
  });

  let simulationOnlyCases = 0;
  const cases = (local.cases ?? []).map((entry, index) => {
    const path = `cases[${index}]`;
    const recorded = pick(
      entry,
      [
        "after",
        "arguments",
        "before",
        "expected",
        "expiresAtLedger",
        "invokedBy",
        "issue",
        "name",
        "observedAtLedger",
        "operation",
        "recordedOn",
        "sessionId",
        "simulation",
        "transactionHash",
        "actual",
      ],
      path,
      unknown,
    );
    recorded.before = snapshot(recorded.before, `${path}.before`, unknown);
    recorded.after = snapshot(recorded.after, `${path}.after`, unknown);
    recorded.expected = pick(recorded.expected ?? {}, ["error", "outcome"], `${path}.expected`, unknown);
    recorded.arguments = pick(recorded.arguments ?? {}, ["actualAmount", "usageHash"], `${path}.arguments`, unknown);
    recorded.stateUnchanged = JSON.stringify(recorded.before) === JSON.stringify(recorded.after);

    if (recorded.recordedOn === "ledger") {
      const receipt = requireReceipt(receipts, recorded.transactionHash, path);
      if (receipt.sourceAccount !== recorded.invokedBy) {
        throw new ManifestGenerationError(`${path} receipt source does not match the invoking account`);
      }
      delete recorded.simulation;
      delete recorded.observedAtLedger;
      // The on-ledger outcome is taken from the network receipt, never from the runner.
      recorded.actual = {
        outcome: receipt.status === "SUCCESS" ? "success" : "failure",
        error: receipt.status === "SUCCESS" ? null : receipt.hostError ?? null,
      };
      Object.assign(recorded, receiptFields(receipt), {
        expectedSuccessful: recorded.expected.outcome === "success",
        resultCode: receipt.resultCode,
      });
    } else if (recorded.recordedOn === "simulation-only") {
      simulationOnlyCases += 1;
      recorded.transactionHash = null;
      recorded.actual = pick(recorded.actual ?? {}, ["error", "outcome"], `${path}.actual`, unknown);
      recorded.simulation = pick(recorded.simulation ?? {}, ["error", "latestLedger"], `${path}.simulation`, unknown);
    } else {
      throw new ManifestGenerationError(`${path} must be recorded on ledger or labelled simulation-only`);
    }
    return recorded;
  });

  failOnUnknown(unknown);

  const limitations = [
    "LBT is a custom test-only token and must not be represented as Circle USDC.",
    "This evidence is for Stellar testnet and makes no mainnet claim.",
    "Rejected cases recorded on ledger were submitted unsimulated with a footprint taken from a valid sibling simulation, so the network rather than the CLI rejected them; their fees were paid in testnet XLM.",
  ];
  if (simulationOnlyCases > 0) {
    limitations.push(
      "Cases labelled simulation-only were rejected during RPC simulation and have no transaction hash; they are not on-ledger results.",
    );
  }

  const document = {
    schemaVersion: 1,
    kind: "live-rejection-evidence",
    environment: "testnet",
    network: { ...testnetNetwork },
    sourceCommit: local.sourceCommit,
    deploymentManifest: local.deploymentManifest,
    contractId: local.contractId,
    asset: pick(local.asset ?? {}, ["code", "contractId", "decimals", "purpose"], "asset", unknown),
    actors: pick(local.actors ?? {}, ["admin", "buyer", "seller", "wrongBuyer", "wrongSeller"], "actors", unknown),
    expiryBoundary: {
      rule: "ledger.sequence >= expires_at_ledger rejects settle and cancel",
      source: "contracts/upto-session/src/validation.rs validate_settlement_amount; contracts/upto-session/src/lib.rs cancel",
      lastValidLedger: "expires_at_ledger - 1",
    },
    setupTransactions,
    cases,
    limitations,
  };
  failOnUnknown(unknown);
  const dates = [...setupTransactions, ...cases].map((entry) => entry.createdAt).filter(Boolean);
  return { document, dropped: dropped.sort(), date: earliestDate(dates) };
}

function snapshot(value, path, unknown) {
  if (value === undefined) {
    throw new ManifestGenerationError(`${path} is missing a state snapshot`);
  }
  const output = pick(value, ["balances", "liability", "session"], path, unknown);
  output.session = pick(
    output.session ?? {},
    ["escrowedAmount", "maxAmount", "settledAmount", "status"],
    `${path}.session`,
    unknown,
  );
  output.balances = pick(
    output.balances ?? {},
    ["buyer", "escrowContract", "seller", "wrongBuyer", "wrongSeller"],
    `${path}.balances`,
    unknown,
  );
  return output;
}

function receiptFields(receipt) {
  return {
    ledger: receipt.ledger,
    createdAt: receipt.createdAt,
    sourceAccount: receipt.sourceAccount,
  };
}

function requireTestnet(network) {
  if (network !== "testnet") {
    throw new ManifestGenerationError(
      `Unsupported network ${JSON.stringify(network ?? null)}; only testnet manifests can be generated`,
    );
  }
}

function requireReceipt(receipts, hash, path) {
  const receipt = typeof hash === "string" ? receipts.get(hash) : undefined;
  if (!receipt) {
    throw new ManifestGenerationError(`Missing network receipt for ${path}`);
  }
  const allowed = new Set([
    "createdAt",
    "hostError",
    "ledger",
    "network",
    "networkPassphrase",
    "resultCode",
    "schemaVersion",
    "sourceAccount",
    "status",
    "transactionHash",
  ]);
  const unknownReceiptFields = Object.keys(receipt).filter((key) => !allowed.has(key));
  if (unknownReceiptFields.length > 0) {
    throw new ManifestGenerationError(
      `Receipt for ${path} has unknown fields`,
      unknownReceiptFields.map((key) => `receipt.${key}`),
    );
  }
  if (
    receipt.schemaVersion !== 1 ||
    receipt.network !== "testnet" ||
    receipt.networkPassphrase !== testnetNetwork.passphrase ||
    receipt.transactionHash !== hash
  ) {
    throw new ManifestGenerationError(`Receipt for ${path} is not a testnet receipt for that transaction`);
  }
  if (!Number.isInteger(receipt.ledger) || Number.isNaN(Date.parse(receipt.createdAt ?? ""))) {
    throw new ManifestGenerationError(`Receipt for ${path} has no network ledger or close time`);
  }
  return receipt;
}

function requireSuccessfulReceipt(receipt, path) {
  if (receipt.status !== "SUCCESS") {
    throw new ManifestGenerationError(`Receipt for ${path} is not a successful transaction`);
  }
}

function pick(source, keys, path, unknown) {
  const output = {};
  for (const key of Object.keys(source ?? {})) {
    if (keys.includes(key)) {
      output[key] = source[key];
    } else {
      unknown.push(`${path}.${key}`);
    }
  }
  return output;
}

function failOnUnknown(unknown) {
  if (unknown.length > 0) {
    throw new ManifestGenerationError("Input contains unknown fields; nothing was written", [
      ...new Set(unknown),
    ].sort());
  }
}

function collectCreatedAt(contracts) {
  return Object.values(contracts).flatMap((contract) =>
    ["upload", "deploy", "initialize"].map((operation) => contract[operation].createdAt),
  );
}

function earliestDate(timestamps) {
  if (timestamps.length === 0) {
    throw new ManifestGenerationError("No network timestamps were available to date the manifest");
  }
  return [...timestamps].sort()[0].slice(0, 10);
}

function sortKeys(value) {
  if (Array.isArray(value)) {
    return value.map(sortKeys);
  }
  if (value === null || typeof value !== "object") {
    return value;
  }
  return Object.fromEntries(
    Object.keys(value)
      .sort()
      .map((key) => [key, sortKeys(value[key])]),
  );
}
